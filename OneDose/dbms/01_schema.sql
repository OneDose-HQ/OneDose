-- Purpose: Create the whole database structure: all tables, primary and foreign keys, CHECK and UNIQUE constraints, basic indexes.
--   Tables: sources, ingredients, drug_classes, ingredient_classes, brands, brand_ingredients, indications,
--   ingredient_indications, conditions, interactions, class_interactions, contraindications, dose_limits,
--   clinicians, patients, patient_allergies, patient_conditions, prescriptions, prescription_items, alerts,
--   consents, rfid_cards, devices, card_scans, audit_log.
--   RUN THIS FIRST and share it with Sivani.
-- Inputs: none
-- Outputs: An empty database structure.
-- Depends on: none
--
-- Engine: PostgreSQL 15+ (uses pg_trgm, pgcrypto, btree_gist, enums, exclusion constraints).
--
-- Conventions
--   * Strengths and doses are stored in mg. Convert mcg/g to mg at load time.
--   * Ingredient pairs are stored ONCE with ingredient_a < ingredient_b.
--   * Rule rows (interactions, contraindications, dose_limits) keep a source_id.
--   * valid_to / end_date NULL means "still open".
--   * Reference tables use GENERATED BY DEFAULT identity so CSV ids load as given.
--     After loading, 02_seed_reference.sql must reset each sequence (setval).
--   * Alerts and audit_log are append-only (blocking triggers live in 07).
--   * Performance indexes are in section 12 so benchmarks.sql can drop and
--     recreate them for the before/after EXPLAIN ANALYZE run.
-- All patient data is synthetic. Prototype, not a medical device.

-- ---------------------------------------------------------------------
-- 0. Optional clean reset (uncomment ONLY on a dev database)
-- ---------------------------------------------------------------------
-- DROP SCHEMA public CASCADE;
-- CREATE SCHEMA public;

-- ---------------------------------------------------------------------
-- 1. Extensions
-- ---------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS pg_trgm;      -- fuzzy brand search
CREATE EXTENSION IF NOT EXISTS pgcrypto;     -- digest() for hashes
CREATE EXTENSION IF NOT EXISTS btree_gist;   -- exclusion constraints on =

-- ---------------------------------------------------------------------
-- 2. Enumerated types
--    Enum order = sort order, so ORDER BY severity DESC ranks correctly.
-- ---------------------------------------------------------------------
CREATE TYPE severity_level  AS ENUM ('minor', 'moderate', 'major', 'critical');
CREATE TYPE check_type      AS ENUM ('duplicate', 'interaction', 'allergy',
                                     'contraindication', 'dose_limit');
CREATE TYPE alert_status    AS ENUM ('open', 'accepted', 'overridden', 'dismissed');
CREATE TYPE clinician_role  AS ENUM ('clinician', 'pharmacist', 'admin');
CREATE TYPE sex_type        AS ENUM ('female', 'male', 'other');

-- ---------------------------------------------------------------------
-- 3. Sources (every rule row points here)
-- ---------------------------------------------------------------------
CREATE TABLE sources (
    source_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text NOT NULL UNIQUE,          -- e.g. 'DDInter', 'openFDA label'
    license       text NOT NULL,                 -- e.g. 'CC BY-NC-SA 4.0'
    url           text,
    retrieved_on  date,
    reviewed_by   text,                          -- pharmacist/doctor who reviewed
    reviewed_on   date
);

-- ---------------------------------------------------------------------
-- 4. Drug knowledge
-- ---------------------------------------------------------------------
CREATE TABLE ingredients (
    ingredient_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text NOT NULL UNIQUE,          -- generic name, lower case
    atc_code      text,
    CONSTRAINT ingredients_name_lower CHECK (name = lower(name))
);

-- Self-referencing tree: e.g. Penicillins -> Beta-lactams -> Antibiotics
CREATE TABLE drug_classes (
    class_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text NOT NULL UNIQUE,
    parent_class_id integer REFERENCES drug_classes(class_id),
    CONSTRAINT drug_classes_not_own_parent CHECK (parent_class_id <> class_id)
);

CREATE TABLE ingredient_classes (
    ingredient_id integer NOT NULL REFERENCES ingredients(ingredient_id),
    class_id      integer NOT NULL REFERENCES drug_classes(class_id),
    PRIMARY KEY (ingredient_id, class_id)
);

CREATE TABLE brands (
    brand_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_name    text NOT NULL,                 -- 'Dolo 650', 'Augmentin 625'
    manufacturer  text,
    form          text,                          -- tablet, syrup, injection ...
    strength      text,                          -- display label only, e.g. '650 mg'; real strengths live in brand_ingredients
    UNIQUE (brand_name, manufacturer)
);

-- One row per active ingredient of a brand. Combination tablets have >1 row.
CREATE TABLE brand_ingredients (
    brand_id      integer NOT NULL REFERENCES brands(brand_id),
    ingredient_id integer NOT NULL REFERENCES ingredients(ingredient_id),
    strength_mg   numeric(10,3) NOT NULL CHECK (strength_mg > 0),  -- per unit (tablet/5 ml)
    PRIMARY KEY (brand_id, ingredient_id)
);

CREATE TABLE indications (
    indication_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text NOT NULL UNIQUE           -- 'fever', 'hypertension' ...
);

CREATE TABLE ingredient_indications (
    ingredient_id   integer NOT NULL REFERENCES ingredients(ingredient_id),
    indication_id   integer NOT NULL REFERENCES indications(indication_id),
    line_of_therapy smallint NOT NULL DEFAULT 1 CHECK (line_of_therapy BETWEEN 1 AND 4),
    PRIMARY KEY (ingredient_id, indication_id)
);

-- ---------------------------------------------------------------------
-- 5. Rules
-- ---------------------------------------------------------------------
-- Coded diagnoses (ICD-10)
CREATE TABLE conditions (
    condition_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    icd10_code    text UNIQUE,
    name          text NOT NULL UNIQUE
);

-- Ingredient-ingredient interaction, pair stored once
CREATE TABLE interactions (
    interaction_id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ingredient_a   integer NOT NULL REFERENCES ingredients(ingredient_id),
    ingredient_b   integer NOT NULL REFERENCES ingredients(ingredient_id),
    severity       severity_level NOT NULL,
    mechanism      text,
    management     text,
    source_id      integer NOT NULL REFERENCES sources(source_id),
    CONSTRAINT interactions_ordered CHECK (ingredient_a < ingredient_b),
    CONSTRAINT interactions_pair_unique UNIQUE (ingredient_a, ingredient_b)
);

-- Class-level interaction (expanded through the class tree by a recursive CTE)
CREATE TABLE class_interactions (
    class_interaction_id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    class_a     integer NOT NULL REFERENCES drug_classes(class_id),
    class_b     integer NOT NULL REFERENCES drug_classes(class_id),
    severity    severity_level NOT NULL,
    mechanism   text,
    management  text,
    source_id   integer NOT NULL REFERENCES sources(source_id),
    CONSTRAINT class_interactions_ordered CHECK (class_a < class_b),
    CONSTRAINT class_interactions_pair_unique UNIQUE (class_a, class_b)
);

CREATE TABLE contraindications (
    ingredient_id integer NOT NULL REFERENCES ingredients(ingredient_id),
    condition_id  integer NOT NULL REFERENCES conditions(condition_id),
    severity      severity_level NOT NULL,
    note          text,
    source_id     integer NOT NULL REFERENCES sources(source_id),
    PRIMARY KEY (ingredient_id, condition_id)
);

-- Max daily dose per ingredient per age band (age_max_years is exclusive)
CREATE TABLE dose_limits (
    dose_limit_id  integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ingredient_id  integer NOT NULL REFERENCES ingredients(ingredient_id),
    age_min_years  integer NOT NULL DEFAULT 0   CHECK (age_min_years >= 0),
    age_max_years  integer NOT NULL DEFAULT 200,
    max_daily_mg   numeric(10,2) NOT NULL CHECK (max_daily_mg > 0),
    source_id      integer NOT NULL REFERENCES sources(source_id),
    CONSTRAINT dose_limits_band_valid CHECK (age_max_years > age_min_years),
    -- age bands of one ingredient must not overlap
    CONSTRAINT dose_limits_no_overlap EXCLUDE USING gist (
        ingredient_id WITH =,
        int4range(age_min_years, age_max_years) WITH &&
    )
);

-- ---------------------------------------------------------------------
-- 6. Clinicians, patients and their history
-- ---------------------------------------------------------------------
CREATE TABLE clinicians (
    clinician_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     text NOT NULL,
    role          clinician_role NOT NULL DEFAULT 'clinician',
    db_username   text UNIQUE,                   -- maps a login to a DB role (08)
    email         text UNIQUE,
    password_hash text,                          -- bcrypt hash from the API layer
    active        boolean NOT NULL DEFAULT true
);

CREATE TABLE patients (
    patient_id    bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    full_name     text NOT NULL,
    date_of_birth date NOT NULL CHECK (date_of_birth <= current_date),
    sex           sex_type,
    weight_kg     numeric(5,2) CHECK (weight_kg > 0),
    db_username   text UNIQUE,                   -- for the 'patient' DB role (08)
    created_at    timestamptz NOT NULL DEFAULT now()
);

-- Allergy to ONE ingredient or to a WHOLE drug class (exactly one is set)
CREATE TABLE patient_allergies (
    allergy_id    bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    patient_id    bigint NOT NULL REFERENCES patients(patient_id),
    ingredient_id integer REFERENCES ingredients(ingredient_id),
    class_id      integer REFERENCES drug_classes(class_id),
    reaction      text,
    severity      severity_level,
    valid_from    date NOT NULL DEFAULT current_date,
    valid_to      date,
    CONSTRAINT allergy_target_exactly_one
        CHECK ((ingredient_id IS NULL) <> (class_id IS NULL)),
    CONSTRAINT allergy_dates_valid CHECK (valid_to IS NULL OR valid_to > valid_from)
);

CREATE TABLE patient_conditions (
    patient_condition_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    patient_id    bigint  NOT NULL REFERENCES patients(patient_id),
    condition_id  integer NOT NULL REFERENCES conditions(condition_id),
    valid_from    date NOT NULL DEFAULT current_date,
    valid_to      date,
    CONSTRAINT condition_dates_valid CHECK (valid_to IS NULL OR valid_to > valid_from)
);

-- ---------------------------------------------------------------------
-- 7. Prescriptions
-- ---------------------------------------------------------------------
CREATE TABLE prescriptions (
    prescription_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    patient_id      bigint  NOT NULL REFERENCES patients(patient_id),
    clinician_id    integer NOT NULL REFERENCES clinicians(clinician_id),
    created_at      timestamptz NOT NULL DEFAULT now(),
    notes           text,
    -- lets prescription_items carry patient_id and stay consistent
    CONSTRAINT prescriptions_id_patient_unique UNIQUE (prescription_id, patient_id)
);

-- dose_units = tablets (or measures) per intake; doses_per_day = intakes per day
-- Daily mg of an ingredient = dose_units * doses_per_day * strength_mg
CREATE TABLE prescription_items (
    item_id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    prescription_id bigint  NOT NULL,
    patient_id      bigint  NOT NULL,            -- denormalised on purpose: partial index + exclusion
    brand_id        integer NOT NULL REFERENCES brands(brand_id),
    dose_units      numeric(6,2) NOT NULL CHECK (dose_units > 0),
    doses_per_day   numeric(5,2) NOT NULL CHECK (doses_per_day > 0),
    start_date      date NOT NULL DEFAULT current_date,
    end_date        date,                        -- NULL = ongoing
    active_period   daterange GENERATED ALWAYS AS
                        (daterange(start_date, end_date, '[]')) STORED,
    CONSTRAINT item_dates_valid CHECK (end_date IS NULL OR end_date >= start_date),
    CONSTRAINT item_prescription_fk FOREIGN KEY (prescription_id, patient_id)
        REFERENCES prescriptions (prescription_id, patient_id),
    -- one patient cannot take the same brand twice in overlapping periods
    CONSTRAINT item_no_overlap EXCLUDE USING gist (
        patient_id WITH =,
        brand_id   WITH =,
        active_period WITH &&
    )
);

-- ---------------------------------------------------------------------
-- 8. Alerts (rows written by trigger in 07; append-only)
-- ---------------------------------------------------------------------
CREATE TABLE alerts (
    alert_id        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    patient_id      bigint  NOT NULL REFERENCES patients(patient_id),
    clinician_id    integer REFERENCES clinicians(clinician_id),
    brand_id        integer NOT NULL REFERENCES brands(brand_id),   -- brand being prescribed
    item_id         bigint  REFERENCES prescription_items(item_id), -- set once prescribed
    check_type      check_type NOT NULL,
    severity        severity_level NOT NULL,
    ingredient_id   integer REFERENCES ingredients(ingredient_id),  -- the new ingredient
    related_ingredient_id integer REFERENCES ingredients(ingredient_id), -- the other side of the clash
    conflicting_item_id   bigint  REFERENCES prescription_items(item_id),
    mechanism       text,
    source_id       integer REFERENCES sources(source_id),
    explanation     text,                         -- LLM text or fixed template (API fills it)
    status          alert_status NOT NULL DEFAULT 'open',
    override_reason text,
    resolved_by     integer REFERENCES clinicians(clinician_id),
    resolved_at     timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT alert_override_needs_reason CHECK (
        status <> 'overridden' OR length(btrim(coalesce(override_reason, ''))) > 0
    )
);

-- ---------------------------------------------------------------------
-- 9. Consent, cards, devices, scans
-- ---------------------------------------------------------------------
CREATE TABLE consents (
    consent_id    bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    patient_id    bigint NOT NULL REFERENCES patients(patient_id),
    scope         text NOT NULL DEFAULT 'treatment',
    granted_at    timestamptz NOT NULL DEFAULT now(),
    expires_at    timestamptz NOT NULL,
    revoked_at    timestamptz,
    CONSTRAINT consent_dates_valid CHECK (expires_at > granted_at)
);

CREATE TABLE rfid_cards (
    card_id       bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    patient_id    bigint NOT NULL REFERENCES patients(patient_id),
    uid_hash      bytea  NOT NULL UNIQUE,        -- SHA-256 of the card UID, never the raw UID
    issued_at     timestamptz NOT NULL DEFAULT now(),
    active        boolean NOT NULL DEFAULT true,
    CONSTRAINT uid_hash_is_sha256 CHECK (octet_length(uid_hash) = 32)
);

CREATE TABLE devices (
    device_id     integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name          text NOT NULL UNIQUE,          -- 'ward-1-reader'
    api_key_hash  bytea,                         -- device authenticates to /scan
    last_seen_at  timestamptz
);

CREATE TABLE card_scans (
    scan_id       bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    device_id     integer REFERENCES devices(device_id),   -- NULL for the mock-tap button
    card_id       bigint  REFERENCES rfid_cards(card_id),  -- NULL if card unknown
    uid_hash      bytea   NOT NULL,                        -- as received
    scanned_at    timestamptz NOT NULL DEFAULT now(),
    outcome       text NOT NULL CHECK (outcome IN
                    ('matched', 'unknown_card', 'inactive_card', 'no_consent'))
);

-- ---------------------------------------------------------------------
-- 10. Audit log (hash chain computed by trigger in 07)
-- ---------------------------------------------------------------------
CREATE TABLE audit_log (
    audit_id      bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    occurred_at   timestamptz NOT NULL DEFAULT now(),
    actor         text NOT NULL DEFAULT current_user,
    action        text NOT NULL CHECK (action IN ('INSERT', 'UPDATE', 'DELETE', 'READ')),
    table_name    text NOT NULL,
    row_pk        text,
    old_data      jsonb,
    new_data      jsonb,
    prev_hash     bytea,                         -- row_hash of the previous row
    row_hash      bytea                          -- digest(prev_hash || this row's content)
);

-- ---------------------------------------------------------------------
-- 11. Sanity helper: age in whole years at a date (used by dose checks)
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_age_years(dob date, on_date date DEFAULT current_date)
RETURNS integer
LANGUAGE sql IMMUTABLE
AS $$ SELECT date_part('year', age(on_date, dob))::integer $$;

-- ---------------------------------------------------------------------
-- 12. Performance indexes
--     (constraint indexes - PKs, UNIQUEs, GiST exclusions - already exist.)
--     benchmarks.sql drops and recreates these for before/after timings.
-- ---------------------------------------------------------------------
-- Interactions: unique(a,b) covers lookups by a; add b for the reverse side
CREATE INDEX idx_interactions_b            ON interactions (ingredient_b);

-- Brand/ingredient lookups
CREATE INDEX idx_brand_ingredients_ingr    ON brand_ingredients (ingredient_id);
CREATE INDEX idx_ingredient_classes_class  ON ingredient_classes (class_id);
CREATE INDEX idx_drug_classes_parent       ON drug_classes (parent_class_id);
CREATE INDEX idx_ingr_indications_ind      ON ingredient_indications (indication_id);
CREATE INDEX idx_contraindications_cond    ON contraindications (condition_id);

-- Fuzzy brand search (pg_trgm)
CREATE INDEX idx_brands_name_trgm          ON brands USING gin (brand_name gin_trgm_ops);

-- Patient history
CREATE INDEX idx_patient_allergies_patient ON patient_allergies (patient_id);
CREATE INDEX idx_patient_conditions_patient ON patient_conditions (patient_id);
CREATE INDEX idx_prescriptions_patient     ON prescriptions (patient_id);
CREATE INDEX idx_items_patient             ON prescription_items (patient_id);
CREATE INDEX idx_items_brand               ON prescription_items (brand_id);

-- Partial index: ongoing medicines only (the hot path of every check)
CREATE INDEX idx_items_active              ON prescription_items (patient_id, brand_id)
                                           WHERE end_date IS NULL;

-- Alerts: per patient timeline, and analytics (override rate per check)
CREATE INDEX idx_alerts_patient_time       ON alerts (patient_id, created_at DESC);
CREATE INDEX idx_alerts_check_status       ON alerts (check_type, status);

-- Scans, consent, audit
CREATE INDEX idx_consents_patient          ON consents (patient_id, expires_at);
CREATE INDEX idx_card_scans_time           ON card_scans (scanned_at DESC);
CREATE INDEX idx_audit_table_time          ON audit_log (table_name, occurred_at DESC);

